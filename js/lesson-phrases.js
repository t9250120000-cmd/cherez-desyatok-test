/* Реплики разговорного урока «Фонарики теремка». Отдельный каталог и отдельный звуковой
   спрайт audio/lesson.mp3: исходные say и записи не меняются. Временная озвучка, для актёра —
   voice-production/LESSON_ADDENDUM.csv. */
(function(root){
'use strict';
const PH=root.PH, T=PH.T, num=PH.num;
const L={};
L.ui={
  hi:T`Привет! Это я, Бульк. Беда: на крыше теремка погасли три фонарика. Поможешь их зажечь?`,
  choose:T`Как будешь отвечать: голосом или кнопками? Выбирай сам.`,
  micOn:T`Ура! Когда горит зелёный кружок, я слушаю. Скажи «да», если готов.`,
  micTest:T`Слышу тебя! Начинаем.`,
  buttons:T`Хорошо, будем нажимать кнопки. Я рядом.`,
  ch1:T`Первый фонарик. Слушай задание.`,
  ch2:T`Второй фонарик ждёт тебя.`,
  ch3:T`Последний фонарик! Ты почти у цели.`,
  sayIt:T`Скажи ответ вслух.`,
  yesNo:T`Скажи «да» или «нет».`,
  again:T`Не расслышал. Это не ошибка. Скажи ещё раз.`,
  quiet:T`Тихо-тихо. Скажи погромче или нажми кнопки.`,
  tryButtons:T`Наверное, шумно. Давай нажмём кнопки, это тоже здорово.`,
  sayAgain:T`Хорошо. Скажи ответ ещё раз.`,
  hands:T`Сейчас работаем руками: нажимай на слаймиков.`,
  lit1:T`Фонарик загорелся!`,
  lit2:T`Уже два фонарика светят!`,
  lit3:T`Все три фонарика горят! Теремок снова светлый.`,
  together:T`Мы решили вместе, и фонарик всё равно загорелся.`,
  goOn:T`Идём дальше? Скажи «да» или нажми кнопку.`,
  bye:T`Спасибо, друг! Без тебя я бы не справился. Теперь перерыв.`,
  micOff:T`Микрофон выключен. Отвечай кнопками.`,
  helpNoEx:T`Давай ещё раз послушаем задание.`,
  later:T`Ничего, поговорим в другой раз.`
};
L.heard=(n)=>T`Ты сказал ${num(n)}?`;
L.enumerate=function(){
  const out=new Map(); const add=p=>{ if(p&&p.say) out.set(p.say,p.text); };
  Object.values(L.ui).forEach(add);
  for(let n=0;n<=20;n++) add(L.heard(n));
  return out;
};
root.LP=L;
})(typeof window!=='undefined'?window:globalThis);
if(typeof module!=='undefined') module.exports=globalThis.LP;
